<?php
/** Proof — the worker's poll (spec "Pulling"): `php bin/ai_poll.php` pulls the months with source cron; off when the setting is off; a changed imported month refused and logged; a month that did not change is not logged. */
require __DIR__ . '/lib.php';
$bea = as_member(27);
ensure_year(as_member(1));
$sept = ai_doc('2026-06', 'closed', sept_doc()['lines']); $oct = ai_doc('2026-07', 'open', oct_doc()['lines']);
$base = (int) one('SELECT count(*) FROM ai_statements');
$poll = fn (): string => trim((string) shell_exec('php ' . escapeshellarg(dirname(__DIR__, 3) . '/bin/ai_poll.php') . ' 2>&1'));
pdo()->exec('UPDATE gl_settings SET ai_statement_poll = false');
ledger_state(['2026-07' => $oct, '2026-06' => $sept]);
echo "1. The setting\n";
$out = $poll();
ok(str_contains($out, 'the poll is off') && (int) one('SELECT count(*) FROM ai_statements') === $base, 'with ai_statement_poll off the poll pulls nothing');
pdo()->exec('UPDATE gl_settings SET ai_statement_poll = true');
echo "2. A pass\n";
$since = last_activity_id();
$out = $poll();
ok(str_contains($out, 'pulled 2: ') && str_contains($out, '2026-07 new') && str_contains($out, '2026-06 new') && (int) one('SELECT count(*) FROM ai_statements') === $base + 2, 'the poll pulls both months (output: ' . $out . ')');
$rows = activity('ai_statement.pull', $since);
ok(count($rows) === 2 && array_unique(array_column($rows, 'source')) === ['cron'] && array_unique(array_column($rows, 'actor_member_id')) === [null], 'each pull is logged ai_statement.pull with source cron and no actor');
$a = json_decode((string) $rows[0]['after'], true);
ok(in_array($a['period'], ['2026-06', '2026-07'], true) && $a['changed'] === 'new', 'with period, kernel_status and changed = new');
$since = last_activity_id();
$out = $poll();
ok(str_contains($out, 'pulled 2: ') && str_contains($out, 'unchanged') && count(activity('ai_statement.pull', $since)) === 0, 'a second pass finds nothing changed and logs nothing');
echo "3. A month closes; a new month; a changed imported month\n";
$octClosed = ai_doc('2026-07', 'closed', $oct['lines']);
$nov = ai_doc('2026-05', 'open', [ai_line('openai', 'gpt-5', 'Front Office', 'Seamus', 5, 0, '0.5000')]);
ledger_state(['2026-05' => $nov, '2026-07' => $octClosed, '2026-06' => $sept]);
$since = last_activity_id();
$out = $poll();
$rows = activity('ai_statement.pull', $since);
ok(str_contains($out, '2026-05 new') && str_contains($out, '2026-07 updated') && count($rows) === 2 && (string) one("SELECT kernel_status FROM ai_statements WHERE period = '2026-07'") === 'closed', 'a new month is pulled and an open month that closed is updated (two rows logged, September unchanged is not)');
act($bea, '/ap/ai/import.php', ['ai_statement' => stmt_id('2026-06')]);
$changed = sept_doc(); $changed['lines'][0]['amount'] = '55.0000'; $changed = ai_doc('2026-06', 'closed', $changed['lines']);
ledger_state(['2026-05' => $nov, '2026-07' => $octClosed, '2026-06' => $changed]);
$since = last_activity_id();
$out = $poll();
$rows = activity('ai_statement.pull', $since);
$refused = array_values(array_filter($rows, fn ($r) => (json_decode((string) $r['after'], true)['changed'] ?? '') === 'refused'));
ok(str_contains($out, 'refused 1: 2026-06') && str_contains($out, 'different document') && count($refused) === 1 && $refused[0]['source'] === 'cron' && (int) $refused[0]['entity_id'] === stmt_id('2026-06'), 'a changed imported month is refused by the database, reported and logged (changed = refused, source cron); the pass goes on');
ok((string) one("SELECT amount FROM ai_statement_lines WHERE statement_id = :s AND line_no = 1", ['s' => stmt_id('2026-06')]) === '12.3456', 'the books kept the imported document');
echo "4. The OS down: the pass says so and logs it\n";
ledger_state(['2026-05' => $nov], 'down');
$since = last_activity_id();
$out = $poll();
$rows = activity('ai_statement.pull', $since);
ok(str_contains($out, 'The OS did not answer') && count($rows) === 1 && json_decode((string) $rows[0]['after'], true)['changed'] === 'failed' && $rows[0]['source'] === 'cron', 'the list failing: the poll exits with the sentence and logs changed = failed');
ledger_state(['2026-05' => $nov, '2026-07' => $octClosed, '2026-06' => $sept]);
finish();
