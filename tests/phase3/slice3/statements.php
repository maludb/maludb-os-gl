<?php
/** Proof — the four statements (spec "Proof", 1): the trial balance equal and saying so, drafts out of the books, the equation, current earnings, the P&L hand figure, the cash flow check and the bank. */
require dirname(__DIR__) . '/lib.php';
require dirname(__DIR__, 3) . '/app/money_math.php';
$vera = as_member(26); $owner = as_member(1);
$w = world();
$range = 'from=2026-01-01&to=2026-12-31';
echo "1. The trial balance\n";
[$c, $d] = screen($vera, "/statements/trial-balance?as_of=2026-12-31");
$t = $d['data'];
ok($c === 200 && $t['balanced'] === true && $t['debit'] === $t['credit'] && $d['table']['status']['ok'] === true && $d['table']['status']['text'] === 'Debits equal credits', 'the totals are equal and the table says so (' . $t['debit'] . ' each)');
$body = page($vera, '/statements/trial-balance?as_of=2026-12-31')['body'];
ok(str_contains($body, 'id="statement-status"') && str_contains($body, 'bg-success') && str_contains($body, 'Debits equal credits'), 'the screen shows the success badge');
$before = $t['debit'];
[$cc, $bb, $draft] = draft(as_member(27), '2026-07-01', [['account' => '6100', 'debit' => '77'], ['account' => '1010', 'credit' => '70']], 'SMOKE unbalanced draft');
[$c, $d] = screen($vera, '/statements/trial-balance?as_of=2026-12-31');
ok($d['data']['debit'] === $before && $d['data']['balanced'], 'an unbalanced draft changes nothing (drafts are not in the books)');
ok(count(array_filter($d['data']['rows'], fn ($r) => $r['code'] === '1200')) === 1 && array_values(array_filter($d['data']['rows'], fn ($r) => $r['code'] === '1200'))[0]['debit'] === '2008.24', 'the receivable shows 2008.24 (1,000 opening + invoices less receipt and credit)');
echo "2. The profit and loss\n";
[$c, $d] = screen($vera, "/statements/pl?$range");
$p = $d['data'];
ok($c === 200 && $p['income_total'] === '1999.99' && $p['expense_total'] === '4259.80' && $p['net_income'] === '-2259.81', 'the hand figures: income 1,999.99, expenses 4,259.80 (tax in gross), net income -2,259.81');
ok($p['net_income'] === $p['net_check'] && $p['net_income'] === m_sub(m_neg(direct_net('income', '2026-01-01', '2026-12-31')), direct_net('expense', '2026-01-01', '2026-12-31')), 'net income equals gl_net_income() and the sum straight from the lines');
$rent = array_values(array_filter(array_merge(...array_column($p['expense_groups'], 'rows')), fn ($r) => $r['code'] === '6100'))[0];
ok($rent['amount'] === '4000.00', 'rent is 4,000.00 for the two months');
$body = page($vera, "/statements/pl?$range")['body'];
ok(str_contains($body, 'href="/accounts/' . $rent['account_id'] . '?from=2026-01-01&amp;to=2026-12-31"'), 'an account row links to its activity with the same range');
echo "3. The balance sheet\n";
[$c, $d] = screen($vera, '/statements/balance-sheet?as_of=2026-12-31');
$b = $d['data'];
ok($c === 200 && $b['holds'] === true && $d['table']['status']['ok'] && str_contains($d['table']['status']['text'], '✓'), 'the equation holds: ' . $d['table']['status']['text']);
pdo()->exec("SELECT set_config('app.member_id', '1', false)");
ok($b['current_earnings'] === (string) one("SELECT gl_net_income('2026-01-01', '2026-12-31')") && $b['current_earnings'] === '-2259.81', 'current earnings equal gl_net_income() for the year (-2,259.81)');
ok(m_sub($b['totals']['asset']['balance'], m_add($b['totals']['liability']['balance'], $b['totals']['equity']['balance'])) === '0.00', 'assets less liabilities and equity is zero');
$body = page($vera, '/statements/balance-sheet?as_of=2026-12-31')['body'];
ok(str_contains($body, 'Current earnings (not yet closed)'), 'the screen names the unclosed earnings row');
echo "4. The cash flow\n";
[$c, $d] = screen($vera, "/statements/cash-flow?$range");
$f = $d['data'];
$bank = (string) one("SELECT COALESCE(sum(l.debit - l.credit), 0) FROM journal_lines l JOIN journal_entries e ON e.id = l.entry_id AND e.status IN ('posted', 'reversed') JOIN accounts a ON a.id = l.account_id WHERE a.is_bank AND e.entry_date <= '2026-12-31'");
ok($c === 200 && m_cmp($f['check'], '0') === 0 && $f['cash_end'] === $bank && $bank === '11000.00', 'the check row is zero and cash at the end equals the bank accounts (' . $bank . ')');
ok($f['cash_end'] === m_add($f['cash_start'], $f['net_change']), 'cash at the end is the start plus the net change');
$body = page($vera, "/statements/cash-flow?$range")['body'];
ok(str_contains($body, 'id="statement-check"') && str_contains($body, 'data-ok="yes"') && str_contains($body, 'Operating activities'), 'the check row and the sections render');
echo "5. The home of the statements\n";
[$c, $d] = screen($vera, '/statements/?period=2026-06');
ok($c === 200 && count($d['statements']) === 4 && array_column($d['statements'], 'statement') === ['pl', 'balance-sheet', 'trial-balance', 'cash-flow'], 'four cards');
$body = page($vera, '/statements/')['body'];
ok(str_contains($body, 'id="statement-card-pl"') && str_contains($body, 'id="statement-card-balance-sheet-state"') && str_contains($body, 'id="posted-through"'), 'the cards carry their state and the posted-through line');
finish();
