<?php
/** Proof — reminders and links (spec "Proof" 3 and 4): the clock's reminders at reminder_days with escalating wording, not again within 7 days, a paid invoice none, empty reminder_days none; a paid invoice's link gets an expiry, a passed expiry answers 404 and is logged once. */
require __DIR__ . '/lib.php';
$bea = as_member(27); $owner = as_member(1);
ensure_year($owner); ar_fixture();
$today = date('Y-m-d');
$ago = fn (int $d): string => date('Y-m-d', strtotime("$today -$d days"));
$cust = mk_customer('SMOKE Slow Payer');
$mk = function (int $daysPastDue) use ($cust, $ago): int { $i = mk_invoice($cust, [['Work', '1', '100.00']], ['issue_date' => $ago($daysPastDue + 30), 'due_date' => $ago($daysPastDue)]); issue($i); return $i; };
pdo()->exec("UPDATE gl_settings SET reminder_days = '{7,21,45}'");
echo "1. Reminders\n";
$i7 = $mk(7); $i8 = $mk(8); $paid = $mk(7);
act($bea, '/receipts/save.php', ['customer' => $cust, 'amount' => '100.00', 'method' => 'cash', 'invoice' => $paid]);
ok(inv_row($paid)['status'] === 'paid', 'a paid invoice 7 days past due (the control)');
$since = last_activity_id();
$r = worker(['--only=reminders']);
ok(($r['results']['reminders']['reminded'] ?? 0) === 1 && $r['errors'] === [], 'one pass reminds one invoice — the one exactly 7 days past due, not 8, not the paid one (' . json_encode($r['results'] ?? $r) . ')');
$row = outbox("kind = 'invoice_reminder' AND record_id = :i", ['i' => $i7])[0] ?? [];
ok(($row['status'] ?? '') === 'queued' && str_contains((string) $row['subject'], 'A friendly reminder') && (int) inv_row($i7)['reminder_count'] === 1 && inv_row($i7)['last_reminder_at'] !== null, 'a step-1 reminder row (friendly wording), reminder_count 1');
ok(count(outbox("kind = 'invoice_reminder' AND record_id IN (:a, :b)", ['a' => $i8, 'b' => $paid])) === 0, 'nothing for the 8-day or the paid invoice');
$lg = activity('invoice.remind_due', $since);
ok(count($lg) === 1 && $lg[0]['source'] === 'cron' && $lg[0]['actor_member_id'] === null && (int) $lg[0]['entity_id'] === $i7 && (int) $lg[0]['customer_id'] === $cust, 'logged invoice.remind_due with source cron, the invoice and the customer');
ok((int) one("SELECT count(*) FROM notifications WHERE kind = 'invoice_overdue' AND record_id = :i AND member_id = 27", ['i' => $i7]) === 1, 'the first reminder tells the holders of ar.write (Bea\'s bell)');
$r = worker(['--only=reminders']);
ok(($r['results']['reminders']['reminded'] ?? -1) === 0, 'a second pass the same day reminds no one again');
$i21 = $mk(21);
$r = worker(['--only=reminders']);
$row = outbox("kind = 'invoice_reminder' AND record_id = :i", ['i' => $i21])[0] ?? [];
ok(str_contains((string) ($row['subject'] ?? ''), '21 days past due'), 'at 21 days: step 2, the firmer wording (' . ($row['subject'] ?? '-') . ')');
$i45 = $mk(45); worker(['--only=reminders']);
ok(str_contains((string) (outbox("kind = 'invoice_reminder' AND record_id = :i", ['i' => $i45])[0]['subject'] ?? ''), 'Final notice'), 'at 45 days: the final notice');
pdo()->exec("UPDATE gl_settings SET reminder_days = '{}'");
$i7b = $mk(7); $r = worker(['--only=reminders']);
ok(($r['results']['reminders']['reminded'] ?? -1) === 0 && count(outbox("kind = 'invoice_reminder' AND record_id = :i", ['i' => $i7b])) === 0, 'reminder_days empty: the worker reminds no one');
pdo()->exec("UPDATE gl_settings SET reminder_days = '{7,21,45}'");
echo "2. Links\n";
$li = mk_invoice($cust, [['Link work', '1', '50.00']], ['issue_date' => $ago(10), 'due_date' => date('Y-m-d', strtotime($today . ' +20 days'))]); issue($li);
act($bea, '/invoices/send.php', ['invoice' => $li]);
$tok = preg_match('#/i/([a-f0-9]{48})#', (string) one("SELECT body FROM notification_outbox WHERE kind = 'invoice_sent' AND record_id = :i ORDER BY id DESC LIMIT 1", ['i' => $li]), $m) ? $m[1] : null;
ok($tok !== null && req('GET', '/i/' . $tok)['code'] === 200, 'a sent invoice\'s secure page opens');
$r = worker(['--only=links']);
$mintExp = one('SELECT expires_at FROM invoice_links_secure WHERE invoice_id = :i AND rotated_at IS NULL', ['i' => $li]);
ok($mintExp !== null && one('SELECT expires_at FROM invoice_links_secure WHERE invoice_id = :i AND rotated_at IS NULL', ['i' => $li]) === $mintExp, 'while the invoice is open its link keeps the life it was minted with and the step leaves it alone');
act($bea, '/receipts/save.php', ['customer' => $cust, 'amount' => '50.00', 'method' => 'cash', 'invoice' => $li]);
$r = worker(['--only=links']);
$exp = one('SELECT expires_at FROM invoice_links_secure WHERE invoice_id = :i AND rotated_at IS NULL', ['i' => $li]);
$paidAt = one('SELECT paid_at FROM invoices WHERE id = :i', ['i' => $li]);
ok(($r['results']['links']['expiry_set'] ?? 0) >= 1 && abs(strtotime((string) $exp) - strtotime((string) $paidAt) - 180 * 86400) < 5, 'paid: the link expires link_lifetime_days (180) after the payment');
ok(req('GET', '/i/' . $tok)['code'] === 200, 'and still opens until then');
$since = last_activity_id();
q("UPDATE invoices SET paid_at = now() - interval '200 days' WHERE id = :i", ['i' => $li]);   // time passes: the payment was 200 days ago
$r = worker(['--only=links']);
ok(req('GET', '/i/' . $tok)['code'] === 404, 'past its expiry (paid 200 days ago, life 180) the secure page answers 404');
$lg = activity('invoice.link_expired', $since);
ok(($r['results']['links']['expired'] ?? 0) === 1 && count($lg) === 1 && $lg[0]['source'] === 'cron' && (int) json_decode((string) $lg[0]['after'], true)['invoice_id'] === $li, 'logged invoice.link_expired once');
$r = worker(['--only=links']);
ok(($r['results']['links']['expired'] ?? -1) === 0 && count(activity('invoice.link_expired', $since)) === 1, 'and not again on the next pass');
finish();
