<?php
/** Proof — the bell and the notices (spec "Proof" 5): a bill drafted → the controller's bell row and email; a payment run → a text when chosen; the morning note sent by the agent's action → the home shows it; period_reopened to the holders of periods.manage; what each person chose decides the email. */
require __DIR__ . '/lib.php';
$bea = as_member(27); $carl = as_member(28); $owner = as_member(1);
ensure_year($owner); ar_fixture(); $fx = ap_fixture();
pdo()->exec("DELETE FROM notification_prefs");
pdo()->exec("UPDATE notification_outbox SET status = 'sent', sent_at = now() WHERE status = 'queued' AND kind <> 'invoice_link'");
echo "1. A bill drafted\n";
$v = mk_vendor('SMOKE Bell Vendor'); $since = last_activity_id();
$bill = mk_bill($v, [['Paper', '1', '40.00']]);
$bell = q("SELECT member_id FROM notifications WHERE kind = 'bill_awaiting' AND record_id = :b ORDER BY member_id", ['b' => $bill]);
$ids = array_map('intval', array_column($bell, 'member_id'));
ok(in_array(28, $ids, true) && in_array(1, $ids, true) && !in_array(27, $ids, true) && !in_array(26, $ids, true) && !in_array(40, $ids, true), 'the approvers (Carl and the owner) get a bell row; the Bookkeeper, the Viewer and the agent do not');
$em = outbox("kind = 'bill_awaiting' AND record_id = :b AND channel = 'email'", ['b' => $bill]);
ok(count($em) === count($ids), 'each of them an email row by the defaults (bill_awaiting is in the default kinds)');
$before = count(mail_log()); worker(['--only=send']);
$sentTo = array_map(fn ($m) => $m['to'], array_slice(mail_log(), $before));
ok(in_array('carl@example.invalid', $sentTo, true) && in_array('owner@example.invalid', $sentTo, true), 'the worker sends them through MaluMail to the directory\'s addresses');
echo "2. What a person chose\n";
pdo()->exec("INSERT INTO notification_prefs (member_id, email_enabled, text_enabled, kinds, text_kinds) VALUES (28, false, false, '{}', '{}'), (1, true, false, '{period_reopened}', '{}')");
$bill2 = mk_bill($v, [['Pens', '1', '10.00']]);
ok((int) one("SELECT count(*) FROM notifications WHERE kind = 'bill_awaiting' AND record_id = :b AND member_id IN (1, 28)", ['b' => $bill2]) === 2, 'the bell row is always written');
ok(count(outbox("record_id = :b AND kind = 'bill_awaiting'", ['b' => $bill2])) === 0, 'Carl switched email off and the owner left bill_awaiting out of their kinds: no email, no text');
[$c, $page] = screen($carl, '/notifications');
ok($c === 200 && count(array_filter($page['notifications'] ?? [], fn ($n) => $n['kind'] === 'bill_awaiting')) >= 2, 'the bell page lists them');
$unread = count($page['notifications'] ?? []);
$n1 = (int) $page['notifications'][0]['notification_id'];
act($carl, '/settings/notifications/read.php', ['notification' => $n1]);
ok((int) one('SELECT count(*) FROM notifications WHERE id = :i AND read_at IS NOT NULL', ['i' => $n1]) === 1, 'reading one marks it read');
echo "3. A payment run and a text\n";
pdo()->exec("DELETE FROM notification_prefs WHERE member_id = 28");
pdo()->exec("INSERT INTO notification_prefs (member_id, email_enabled, text_enabled, kinds, text_kinds) VALUES (28, true, true, '{payment_run_awaiting}', '{payment_run_awaiting}')");
sms_mode('ok');
$b1 = ready_bill($v, [['Run item', '1', '75.00']]);
$smsBefore = count(sms_log());
[$c, $b] = act($bea, '/payment-runs/save.php', ['bank_account' => $fx['bank'], 'pay_date' => '2026-07-02', 'bills' => [$b1]]);
$run = (int) ($b['record_id'] ?? 0);
$tx = outbox("channel = 'text' AND member_id = 28 AND kind = 'payment_run_awaiting'");
ok($run > 0 && count($tx) === 1, 'a payment run awaiting approval queues Carl a text, as he chose' . ($run === 0 ? ' (' . msg($b) . ')' : ''));
worker(['--only=send']);
ok(count(sms_log()) === $smsBefore + 1 && outbox('id = :i', ['i' => $tx[0]['id'] ?? 0])[0]['status'] === 'sent', 'and the worker sends it through K6');
echo "4. Periods\n";
$pid = (int) one("SELECT id FROM fiscal_periods WHERE name = '2026-01'");
if ($pid === 0) { $pid = (int) one("SELECT id FROM fiscal_periods ORDER BY start_date LIMIT 1"); }
act($carl, '/periods/close.php', ['period' => $pid]);
$closed = q("SELECT member_id FROM notifications WHERE kind = 'period_closed' AND record_id = :p", ['p' => $pid]);
ok(count($closed) >= 1 && in_array(28, array_map('intval', array_column($closed, 'member_id')), true) && !in_array(27, array_map('intval', array_column($closed, 'member_id')), true), 'closing a period tells the holders of periods.manage (Carl) and not the Bookkeeper');
pdo()->exec("DELETE FROM notification_prefs WHERE member_id IN (1, 28)");
pdo()->exec("INSERT INTO notification_prefs (member_id, email_enabled, text_enabled, kinds, text_kinds) VALUES (28, true, false, '{period_reopened}', '{}')");
[$c, $b] = act($carl, '/periods/reopen.php', ['period' => $pid, 'reason' => 'SMOKE: a late bill']);
$o = q("SELECT member_id FROM notifications WHERE kind = 'period_reopened' AND record_id = :p", ['p' => $pid]);
ok($c === 200 && count($o) >= 1 && count(outbox("kind = 'period_reopened' AND record_id = :p AND channel = 'email'", ['p' => $pid])) >= 1, 'reopening tells them again, with an email where they chose it (' . $c . ' ' . msg($b) . ')');
echo "5. The morning note\n";
pdo()->exec("UPDATE gl_settings SET morning_note_member_id = 28");
pdo()->exec("DELETE FROM notification_prefs WHERE member_id = 28");
$agent = ['X-Action-Token: ' . person_token(40)];
[$c, $b] = act_token('/settings/agents/morning-note.php', ['body' => "Imported September's AI bills (3).\nNeeds a person: bill SMOKE-1 has no document."], $agent);
ok($c === 200 && ($b['ok'] ?? false) && (int) ($b['to_member_id'] ?? 0) === 28, 'the Bookkeeper agent\'s morning_note_send reaches the member the settings name');
$note = q("SELECT * FROM notifications WHERE kind = 'morning_note' AND member_id = 28 ORDER BY id DESC LIMIT 1")[0] ?? [];
ok(str_starts_with((string) ($note['title'] ?? ''), 'Morning note: Imported September') && str_contains((string) ($note['body'] ?? ''), 'no document'), 'a bell row of kind morning_note with the body');
$rows = q("SELECT * FROM activity_log WHERE action = 'morning_note.send' ORDER BY id DESC LIMIT 1");
ok(count($rows) === 1 && !str_contains((string) $rows[0]['after'], 'Needs a person') && json_decode((string) $rows[0]['after'], true)['length'] > 20, 'logged morning_note.send with the length, never the body ');
[$c, $home] = screen($carl, '/');
ok($c === 200 && str_contains(json_encode($home), 'Imported September'), 'the home shows it to Carl');
[$c, $b] = act_token('/settings/agents/morning-note.php', ['body' => ''], $agent);
ok($c === 422 && isset(fields($b)['body']), 'an empty note is refused');
[$c, $b] = act_token('/settings/agents/morning-note.php', ['body' => 'x', 'to_member' => 40], $agent);
ok($c === 422 && isset(fields($b)['to_member']), 'a note to an agent is refused (people only)');
pdo()->exec("UPDATE gl_settings SET morning_note_member_id = NULL");
[$c, $b] = act_token('/settings/agents/morning-note.php', ['body' => 'x'], $agent);
ok($c === 422 && str_contains(msg($b), 'No one is named'), 'with no one named and no to_member the refusal says so');
[$c, $b] = act_token('/settings/agents/morning-note.php', ['body' => 'x'], ['X-Action-Token: ' . person_token(26)]);
ok($c === 403, 'a Viewer cannot send one');
finish();
