<?php
/** Proof — agents (spec "Proof", 7): under the Bookkeeper's run token a draft with lines as JSON (accounts by code), source agent with the run's request id; post runs; an unknown code names the row; an eval run writes nothing. */
require __DIR__ . '/lib.php';
$owner = as_member(1);
ensure_year($owner);
kernel_state(function ($st) { $st['facts']['91'] = ['valid' => true, 'is_agent' => true, 'member_id' => 40, 'run_id' => 91, 'request_id' => 'req-run-91', 'trigger' => 'duty', 'is_eval' => false, 'endpoints' => [['name' => 'Records MCP']]];
    $st['facts']['92'] = ['valid' => true, 'is_agent' => true, 'member_id' => 40, 'run_id' => 92, 'request_id' => 'req-run-92', 'trigger' => 'eval', 'is_eval' => true, 'endpoints' => [['name' => 'Records MCP']]]; return $st; });
[$tok, $relay] = run_token(40, 91);
$h = ['X-Action-Token: ' . $tok, 'X-Action-Relay: ' . $relay];
echo "1. A draft by the agent\n";
$since = last_activity_id();
[$c, $b] = act_token('/journal/save.php', ['entry_date' => '2026-08-03', 'memo' => 'SMOKE agent accrual', 'lines' => json_encode([['account' => '6200', 'debit' => '259.80', 'description' => 'Hosting'], ['account' => '2000', 'credit' => '259.80', 'vendor' => null]])], $h);
$id = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $id > 0 && ($b['ok'] ?? false) && ($b['location'] ?? '') === '/journal/' . $id . '?notice=saved', 'journal_entry_draft under the run token: {ok, record_id, location}');
$row = q("SELECT source, agent_run_id, request_id FROM activity_log WHERE action = 'journal_entry.draft' AND id > :s ORDER BY id DESC LIMIT 1", ['s' => $since])[0];
ok($row['source'] === 'agent' && (int) $row['agent_run_id'] === 91 && $row['request_id'] === 'req-run-91' && (int) one('SELECT created_by FROM journal_entries WHERE id = :i', ['i' => $id]) === 40, 'source agent, run 91, the run\'s request id; created by the agent (40)');
$body = page($owner, '/journal/' . $id)['body'];
ok(str_contains($body, 'badge bg-soft-info text-info">agent</span>'), 'the entry page chips the agent');
[$c, $b] = act_token('/journal/save.php', ['entry_date' => '2026-08-03', 'lines' => json_encode([['account' => '6200', 'debit' => '1'], ['account' => 'XYZ-nope', 'credit' => '1']])], $h);
ok($c === 422 && str_contains(msg($b), 'Row 2: no account called XYZ-nope') && (fields($b)['row'] ?? 0) === 2, 'an unknown account code in row 2: 422 naming the row');
echo "2. Post by the agent (the pause is the kernel's)\n";
q('INSERT INTO vendors (name) VALUES (\'SMOKE Hosting Co\') ON CONFLICT DO NOTHING');
$vend = (int) one("SELECT id FROM vendors WHERE name = 'SMOKE Hosting Co'");
$l2 = (int) one('SELECT id FROM journal_lines WHERE entry_id = :e AND line_no = 2', ['e' => $id]);
[$c, $b] = act_token('/journal/line-save.php', ['entry' => $id, 'line' => $l2, 'vendor' => $vend], $h);
ok($c === 200, 'the agent names the vendor on the payable line');
$since = last_activity_id();
[$c, $b] = act_token('/journal/post.php', ['entry' => $id], $h);
ok($c === 200 && str_starts_with((string) $b['number'], 'JE-') && entry_status($id) === 'posted', 'journal_entry_post runs under the run token (the approval pause lives in the kernel): posted');
$row = q("SELECT source, agent_run_id FROM activity_log WHERE action = 'journal_entry.post' AND id > :s", ['s' => $since])[0];
ok($row['source'] === 'agent' && (int) $row['agent_run_id'] === 91, 'journal_entry.post is the agent\'s row');
echo "3. An eval run writes nothing\n";
[$tok2, $relay2] = run_token(40, 92);
$h2 = ['X-Action-Token: ' . $tok2, 'X-Action-Relay: ' . $relay2];
$before = (int) one('SELECT count(*) FROM journal_entries');
[$c, $b] = act_token('/journal/save.php', ['entry_date' => '2026-08-04', 'memo' => 'SMOKE eval', 'lines' => '[]'], $h2);
ok($c === 403 && msg($b) === 'An evaluation run writes nothing.' && (int) one('SELECT count(*) FROM journal_entries') === $before, 'is_eval: 403 "An evaluation run writes nothing." and no row');
$r = req('GET', '/journal/' . $id, ['headers' => array_merge(JSONH, $h2)]);
ok($r['code'] === 200, 'but it reads (200)');
echo "4. The relay\n";
[$c, $b] = act_token('/journal/save.php', ['entry_date' => '2026-08-05', 'lines' => '[]'], ['X-Action-Token: ' . $tok]);
ok($c === 401, 'a run token without the relay: 401');
kernel_state(function ($st) { unset($st['facts']); return $st; });
finish();
